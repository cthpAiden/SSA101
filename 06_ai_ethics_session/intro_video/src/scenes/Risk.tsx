import React from 'react';
import cues from '../cues.json';
import {Scene, Kicker} from '../frame';
import {C, Cursor, EIO, F, FadeUp, Label, Letters, pr, sp, typedChars, useT} from '../lib';

const R = cues.risk;
export const CITATION = 'See Varghese v. China Southern Airlines Co., 925 F.3d 1339 (11th Cir. 2019).';
export const citeStep = (R.cite[1] - R.cite[0]) / CITATION.length;

const Bar: React.FC<{w: string}> = ({w}) => <div style={{width: w, height: 11, borderRadius: 6, background: 'rgba(14,27,44,0.09)', marginTop: 16}} />;

export const Risk: React.FC = () => {
  const t = useT();
  const docIn = sp(t, R.doc, 16, 120);
  const typed = typedChars(t, R.cite[0], citeStep, CITATION.length);
  const typing = t >= R.cite[0] && t < R.cite[1] + 0.15;
  const scan = pr(t, R.scan[0], R.scan[1] - R.scan[0], EIO);
  const found = t >= R.result;
  const stamp = sp(t, R.stamp, 18, 420);
  const strike = pr(t, R.stamp + 0.15, 0.45, EIO);
  const out = 0;
  const tilt = (1 - docIn) * -40 + Math.sin(t * 0.8) * 1.5;

  return (
    <Scene start={R.start} end={R.end}>
      <div style={{position: 'absolute', left: 150, top: 150}}>
        <Kicker num="03" text="Risk" at={R.start + 0.3} />
      </div>
      <div style={{position: 'absolute', left: 150, top: 196, fontFamily: F.display, fontSize: 68, letterSpacing: '-0.015em', color: C.white}}>
        <Letters text="When AI invents a source" at={R.start + 0.5} mode="rise" stagger={0.018} />
      </div>

      {/* phase A: the brief in 3D */}
      <div
        style={{
          position: 'absolute',
          inset: 0,
          perspective: 1600,
          perspectiveOrigin: '40% 50%',
          opacity: 1 - out,
          transform: `scale(${1 + out * 1.4})`,
          filter: out > 0 ? `blur(${out * 14}px)` : undefined,
        }}
      >
        <div
          style={{
            position: 'absolute',
            left: 170,
            top: 320,
            width: 880,
            height: 600,
            transform: `rotateY(${tilt}deg) rotateX(${(1 - docIn) * 12 + Math.sin(t * 0.6) * 1.2}deg) translateZ(${(1 - docIn) * -400}px)`,
            transformOrigin: '50% 50%',
            opacity: Math.min(1, docIn * 1.5),
            background: 'linear-gradient(160deg, #FFFDF8, #F0EBDF)',
            boxShadow: '0 60px 120px rgba(0,0,0,0.6), 0 0 0 1px rgba(255,255,255,0.15)',
            padding: '44px 56px',
            color: C.ink,
          }}
        >
          <Label size={12} color="#6B7390">
            United States District Court
          </Label>
          <Label size={12} color="#6B7390" style={{marginTop: 4}}>
            Southern District of New York
          </Label>
          <div style={{fontFamily: F.deck, fontStyle: 'italic', fontSize: 46, marginTop: 18}}>Mata v. Avianca, Inc.</div>
          <Label size={11} color="#8A91A3" style={{marginTop: 8}}>
            Filed brief · Excerpt
          </Label>
          <div style={{height: 1, background: 'rgba(14,27,44,0.15)', marginTop: 20}} />
          <Bar w="100%" />
          <Bar w="93%" />
          <Bar w="70%" />
          <div style={{marginTop: 26, opacity: pr(t, R.cite[0] - 0.3, 0.3)}}>
            <Label size={11} color={C.machineDeep}>
              Generated by ChatGPT
            </Label>
            <div
              style={{
                marginTop: 8,
                padding: '12px 18px',
                minHeight: 98,
                background: 'rgba(46,91,216,0.08)',
                borderLeft: `3px solid ${C.machineDeep}`,
                fontFamily: F.mono,
                fontSize: 25,
                lineHeight: 1.55,
              }}
            >
              <span
                style={{
                  backgroundImage: `linear-gradient(${C.redDeep}, ${C.redDeep})`,
                  backgroundRepeat: 'no-repeat',
                  backgroundPosition: '0 58%',
                  backgroundSize: `${strike * 100}% 3px`,
                }}
              >
                {CITATION.slice(0, typed)}
              </span>
              {typing && <Cursor on color={C.machineDeep} />}
            </div>
          </div>
          <Bar w="88%" />
          <Bar w="52%" />
          {/* scan beam */}
          {t >= R.scan[0] && t < R.result + 0.2 && (
            <div
              style={{
                position: 'absolute',
                left: 0,
                right: 0,
                top: `${scan * 100}%`,
                height: 3,
                background: C.machine,
                boxShadow: `0 0 30px 6px rgba(125,183,255,0.7)`,
                opacity: 1 - pr(t, R.result, 0.2),
              }}
            />
          )}
          {stamp > 0 && (
            <div
              style={{
                position: 'absolute',
                left: 90,
                top: 350,
                transform: `rotate(-11deg) scale(${Math.max(1, 2.6 - 1.6 * stamp)})`,
                opacity: Math.min(1, stamp * 2) * 0.92,
                border: `7px solid ${C.redDeep}`,
                outline: `2px solid ${C.redDeep}`,
                outlineOffset: 5,
                padding: '8px 28px 2px',
                fontFamily: F.black,
                fontSize: 74,
                letterSpacing: '0.1em',
                color: C.redDeep,
                mixBlendMode: 'multiply',
              }}
            >
              FABRICATED
            </div>
          )}
        </div>

        {/* verification panel */}
        <div style={{position: 'absolute', left: 1110, top: 330, width: 710}}>
          <FadeUp at={R.scan[0] - 0.4} dist={10}>
            <Label size={13} color={C.machine}>
              Verification
            </Label>
            <div style={{height: 1, background: 'rgba(255,255,255,0.25)', marginTop: 12}} />
          </FadeUp>
          {(
            [
              ['Query', 'Varghese v. China Southern Airlines', R.scan[0]],
              ['Source', 'Federal Reporter, 925 F.3d 1339', R.scan[0] + 0.35],
              ['Status', found ? 'No such case exists' : 'Searching court records', R.scan[0] + 0.7],
            ] as [string, string, number][]
          ).map(([k, v, at]) => (
            <FadeUp key={k} at={at} dist={8} style={{display: 'flex', marginTop: 16, fontFamily: F.mono, fontSize: 25}}>
              <span style={{width: 118, color: C.soft, flexShrink: 0}}>{k}</span>
              <span style={{color: k === 'Status' && found ? C.red : C.white}}>{v}</span>
            </FadeUp>
          ))}
          <div style={{marginTop: 26, height: 5, background: 'rgba(255,255,255,0.1)', opacity: pr(t, R.scan[0], 0.3)}}>
            <div style={{width: `${scan * 100}%`, height: '100%', background: found ? C.red : C.machine, boxShadow: `0 0 14px ${found ? C.red : C.machine}`}} />
          </div>
          {t >= R.result && (
            <div style={{marginTop: 34, fontFamily: F.black, fontSize: 96, lineHeight: 1, color: C.white, letterSpacing: '-0.02em', whiteSpace: 'nowrap', transform: `scale(${1.25 - 0.25 * Math.min(1, sp(t, R.result, 14, 220))})`, transformOrigin: '0 50%', opacity: Math.min(1, sp(t, R.result, 14, 220) * 2)}}>
              0 <span style={{fontFamily: F.display, fontStyle: 'italic', fontSize: 58, color: C.red}}>records found</span>
            </div>
          )}
          <FadeUp at={R.caption} style={{marginTop: 30}}>
            <div style={{fontFamily: F.sans, fontSize: 30, lineHeight: 1.42, color: C.white}}>
              June 2023: a U.S. federal judge fined two lawyers and their firm{' '}
              <span style={{fontFamily: F.black, color: C.ember, fontSize: 36}}>$5,000</span>. Their brief cited cases that ChatGPT had invented.
            </div>
          </FadeUp>
        </div>
      </div>

    </Scene>
  );
};

